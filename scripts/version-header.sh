#!/bin/sh
# Writes firmware/tdongle_display/version.h from the one version literal in cli/Cargo.toml.
set -eu
cd "$(dirname "$0")/.."
v=$(sed -n 's/^version = "\(.*\)"/\1/p' cli/Cargo.toml | head -n1)
[ -n "$v" ] || { echo "version not found in cli/Cargo.toml" >&2; exit 1; }
printf '// Generated by scripts/version-header.sh from cli/Cargo.toml. Do not edit.\n#define FW_VERSION "%s"\n' "$v" \
  > firmware/tdongle_display/version.h
echo "$v"
